  var lang = 'en';
  var listeners = [];
  try {
    if (localStorage.getItem('indoor.ui.v1.lang') === 'ar') lang = 'ar';
  } catch (e) {}

  function t(key) {
    var pack = STR[lang] || STR.en;
    if (pack[key] != null) return pack[key];
    return STR.en[key] != null ? STR.en[key] : key;
  }

  function place(name) {
    if (!name) return name || '';
    if (lang !== 'ar') return name;
    if (PLACES[name]) return PLACES[name];
    return name;
  }

  function meters(detail) {
    var text = String(detail || '');
    if (lang !== 'ar') return text;
    return text.replace(/\bm\b/g, 'م').replace(/\bkm\b/g, 'كم');
  }

  function stepLine(step) {
    if (!step) return '';
    if (step.kind === 'arrive') return t('arrive') + ' ' + place(step.name || step.detail);
    if (step.kind === 'transition') {
      var ride = step.mode === 'stair' ? t('takeStairs') : step.mode === 'escalator' ? t('takeEscalator') : t('takeElevator');
      var floorName = place(step.level_name);
      return floorName ? ride + ' ' + t('toWord') + ' ' + floorName : ride;
    }
    var dir = String(step.text || '').replace(/^Head\s+/i, '').trim().toLowerCase();
    if (step.action === 'outside') return t('outside');
    if (step.action === 'depart' || dir && STR.en[dir]) return t('head') + ' ' + t(dir);
    var verbs = {
      left: 'turnLeft',
      right: 'turnRight',
      'slight-left': 'bearLeft',
      'slight-right': 'bearRight',
      'sharp-left': 'sharpLeft',
      'sharp-right': 'sharpRight',
      uturn: 'uturn',
      straight: 'continue'
    };
    return t(verbs[step.action] || 'continue');
  }

  function arrival(route) {
    var dest = place(route.to && route.to.name) || t('destination');
    var moves = (route.steps || []).filter(function (step) { return step.kind !== 'arrive'; });
    if (!moves.length) return t('followBlue') + ' ' + dest + '.';
    var bits = moves.slice(0, 4).map(function (step) {
      var line = stepLine(step);
      return step.detail && step.kind !== 'transition' ? line + ' ' + t('forDist') + ' ' + meters(step.detail) : line;
    });
    var sentence = bits[0];
    if (bits.length === 2) sentence += '، ' + t('then') + ' ' + bits[1];
    else if (bits.length > 2) sentence += '، ' + bits.slice(1, -1).join('، ') + '، ' + t('then') + ' ' + bits[bits.length - 1];
    if (moves.length > bits.length) return sentence + '، ' + t('continueOn') + ' ' + dest + '.';
    return sentence + ' ' + t('reach') + ' ' + dest + '.';
  }

  function countPlaces(n) {
    n = Number(n) || 0;
    if (lang !== 'ar') return n + (n === 1 ? ' place' : ' places') + ' on this floor';
    if (n === 1) return 'مكان واحد في هذا الطابق';
    if (n === 2) return 'مكانان في هذا الطابق';
    return n + ' أماكن في هذا الطابق';
  }

  var ERRORS = {
    'Choose a start and a destination.': 'errEnds',
    'That place is not on the map.': 'errMissing',
    'That point is not on the walk network.': 'errPoint',
    'Choose two different places.': 'errDifferent',
    'No route uses only the elevator.': 'errElevator',
    'No route uses only the stairs.': 'errStair',
    'No indoor route connects these places.': 'errNone'
  };

  function error(message) {
    if (lang !== 'ar' || !message) return message;
    if (ERRORS[message]) return t(ERRORS[message]);
    var linked = String(message).match(/^(.*) is not connected to the walk network\.$/);
    if (linked) return place(linked[1]) + ' غير متصل بشبكة المشي.';
    return message;
  }

  function apply() {
    document.documentElement.lang = lang === 'ar' ? 'ar' : 'en';
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.title = t('title');
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
      el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
    });
    document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
    });
  }

  function setLang(next) {
    lang = next === 'ar' ? 'ar' : 'en';
    try { localStorage.setItem('indoor.ui.v1.lang', lang); } catch (e) {}
    apply();
    listeners.forEach(function (fn) { fn(lang); });
  }

  function onChange(fn) {
    listeners.push(fn);
  }

